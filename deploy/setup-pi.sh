#!/usr/bin/env bash
# Infrastructure for CalendarBot v2 on a Raspberry Pi (Debian 12, arm64):
#   - PostgreSQL 15, tuned for ~400 MB RAM, localhost only, password auth
#   - NATS 2.15 with JetStream, localhost only, a dedicated authenticated account
# Writes DATABASE_URL and NATS_URL/NATS_USER/NATS_PASSWORD (random secrets
# generated here, never shown) to the bot's .env.
#
#   sudo bash setup-pi.sh            # safe to re-run
set -euo pipefail

BOT_USER="${SUDO_USER:-br}"
BOT_DIR="${BOT_DIR:-/home/${BOT_USER}/calendarbot-v2}"
ENV_FILE="${BOT_DIR}/.env"
NATS_VERSION="v2.15.3"
[ "$(id -u)" -eq 0 ] || { echo "run with sudo"; exit 1; }

install -d -o "${BOT_USER}" -g "${BOT_USER}" -m 700 "${BOT_DIR}"
touch "${ENV_FILE}" && chown "${BOT_USER}:${BOT_USER}" "${ENV_FILE}" && chmod 600 "${ENV_FILE}"
set_env() { sed -i "/^$1=/d" "${ENV_FILE}"; printf '%s=%s\n' "$1" "$2" >> "${ENV_FILE}"; }
has_env() { grep -q "^$1=" "${ENV_FILE}"; }

echo "==> PostgreSQL"
apt-get update -qq
apt-get install -y -qq postgresql >/dev/null
PG_CONF_DIR="$(ls -d /etc/postgresql/*/main | tail -1)/conf.d"
cat > "${PG_CONF_DIR}/calendarbot.conf" <<'CONF'
# Small-memory tuning for a Pi Zero 2 W
listen_addresses = 'localhost'
shared_buffers = 16MB
max_connections = 20
work_mem = 2MB
maintenance_work_mem = 16MB
effective_cache_size = 96MB
password_encryption = scram-sha-256
CONF
systemctl restart postgresql
if ! sudo -u postgres psql -tAc "select 1 from pg_roles where rolname='calendarbot'" | grep -q 1 || ! has_env DATABASE_URL; then
  PG_PW="$(openssl rand -hex 24)"
  if sudo -u postgres psql -tAc "select 1 from pg_roles where rolname='calendarbot'" | grep -q 1; then
    sudo -u postgres psql -q -c "alter role calendarbot password '${PG_PW}'"
  else
    sudo -u postgres psql -q -c "create role calendarbot login password '${PG_PW}'"
  fi
  sudo -u postgres psql -tAc "select 1 from pg_database where datname='calendarbot'" | grep -q 1 \
    || sudo -u postgres psql -q -c "create database calendarbot owner calendarbot"
  set_env DATABASE_URL "postgres://calendarbot:${PG_PW}@127.0.0.1:5432/calendarbot"
  echo "    role + database ready; DATABASE_URL written to ${ENV_FILE}"
else
  echo "    already configured"
fi

echo "==> NATS ${NATS_VERSION}"
if [ "$(/usr/local/bin/nats-server --version 2>/dev/null | awk '{print $NF}')" != "${NATS_VERSION}" ]; then
  TMP="$(mktemp -d)"; cd "${TMP}"
  ASSET="nats-server-${NATS_VERSION}-linux-arm64.tar.gz"
  BASE="https://github.com/nats-io/nats-server/releases/download/${NATS_VERSION}"
  curl -fsSLO "${BASE}/${ASSET}"
  curl -fsSL "${BASE}/SHA256SUMS" | grep " ${ASSET}\$" | sha256sum -c -
  tar -xzf "${ASSET}"
  install -m 755 "nats-server-${NATS_VERSION}-linux-arm64/nats-server" /usr/local/bin/nats-server
  cd / && rm -rf "${TMP}"
fi
id nats >/dev/null 2>&1 || useradd --system --home-dir /var/lib/nats --create-home --shell /usr/sbin/nologin nats
install -d -o nats -g nats -m 750 /var/lib/nats

if ! has_env NATS_PASSWORD || [ ! -f /etc/nats-server.conf ]; then
  NATS_PW="$(openssl rand -hex 24)"
  set_env NATS_URL "nats://127.0.0.1:4222"
  set_env NATS_USER "calendarbot"
  set_env NATS_PASSWORD "${NATS_PW}"
else
  NATS_PW="$(grep '^NATS_PASSWORD=' "${ENV_FILE}" | cut -d= -f2-)"
fi
umask 027
cat > /etc/nats-server.conf <<CONF
# Generated by setup-pi.sh. See deploy/nats-server.conf.example in the repo.
server_name: pi-nats
listen: 127.0.0.1:4222
http: 127.0.0.1:8222
jetstream {
  store_dir: /var/lib/nats
  max_memory_store: 16MB
  max_file_store: 512MB
}
accounts {
  CALENDARBOT {
    jetstream: { max_mem: 16MB, max_file: 512MB }
    users: [ { user: calendarbot, password: "${NATS_PW}" } ]
  }
}
CONF
chown root:nats /etc/nats-server.conf && chmod 640 /etc/nats-server.conf
cat > /etc/systemd/system/nats.service <<'CONF'
[Unit]
Description=NATS server (JetStream) for CalendarBot
After=network-online.target
Wants=network-online.target

[Service]
User=nats
ExecStart=/usr/local/bin/nats-server -c /etc/nats-server.conf
ExecReload=/bin/kill -HUP $MAINPID
Restart=on-failure
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
CONF
systemctl daemon-reload
systemctl enable nats >/dev/null 2>&1
systemctl restart nats

echo "==> Check"
sleep 2
echo "    postgresql: $(systemctl is-active postgresql)   nats: $(systemctl is-active nats)"
echo "    $(/usr/local/bin/nats-server --version)   healthz: $(curl -fsS http://127.0.0.1:8222/healthz)"
echo "    shared_buffers: $(sudo -u postgres psql -tAc 'show shared_buffers')"
echo "    ${ENV_FILE}: $(sed -E 's/=.*//' "${ENV_FILE}" | tr '\n' ' ')"
free -m | sed -n 2p
echo "Done."
